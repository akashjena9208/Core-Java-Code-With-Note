package sorting;

public class Student {
	String name;
	double percs;
	int age;
	public Student(String name, double percs, int age) {
		super();
		this.name = name;
		this.percs = percs;
		this.age = age;
	}
	@Override
	public String toString() {
		return "Student [name=" + name + ", percs=" + percs + ", age=" + age + "]";
	}
	
	
	
	
	
	

}
